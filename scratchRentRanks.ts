/** Dollars for `spaceIndex` 1..55 at `buildingRank` 0..6 (clamped). */
export function dollarRentFromScratchTable(
  spaceIndex: number,
  buildingRank: number,
): number {
  if (spaceIndex <= 0 || spaceIndex > SCRATCH_RENT_SLOTS) return 0;
  const slot = spaceIndex - 1;
  const r = Math.min(6, Math.max(0, Math.floor(buildingRank)));
  return DOLLAR_RENT_BY_RANK[r]![slot]!;
}
